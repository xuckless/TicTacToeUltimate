type vectorFile struct {
	Rules struct {
		ID string `json:"id"`
	} `json:"rules"`
	Cases []struct {
		Name    string `json:"name"`
		Actions string `json:"actions"`
		Expect  *struct {
			Ply          int    `json:"ply"`
			Phase        string `json:"phase"`
			ToMove       string `json:"toMove"`
			Outcome      string `json:"outcome"`
			Board        string `json:"board"`
			Legal        []int  `json:"legal"`
			NextToVanish *int   `json:"nextToVanish"`
			Swapped      bool   `json:"swapped"`
		} `json:"expect"`
		Error *struct {
			AtIndex int `json:"atIndex"`
		} `json:"error"`
	} `json:"cases"`
	Playouts []struct {
		Actions    string `json:"actions"`
		FinalBoard string `json:"finalBoard"`
		Outcome    string `json:"outcome"`
	} `json:"playouts"`
	Tablebase *struct {
		Reachable   int `json:"reachable"`
		NonTerminal int `json:"nonTerminal"`
		Positions   []struct {
			Actions  string `json:"actions"`
			Value    string `json:"value"`
			Distance int    `json:"distance"`
		} `json:"positions"`
	} `json:"tablebase"`
}

func outcomeOf(s State) string {
	switch {
	case s.Phase != Ended:
		return "None"
	case s.Winner == 0:
		return "XWins"
	case s.Winner == 1:
		return "OWins"
	default:
		return "Draw"
	}
}

func phaseOf(s State) string {
	return [...]string{"AwaitingPlacement", "AwaitingSwapDecision", "Ended"}[s.Phase]
}

// The shared vectors are generated by the C# engine (tools/TicTacToeUltimate.RulesTool); the Go port must agree.
func TestVectors(t *testing.T) {
	files, _ := filepath.Glob("../../../spec/rules/vectors/*.json")
	if len(files) == 0 {
		t.Fatal("no vector files found")
	}
	for _, f := range files {
		raw, _ := os.ReadFile(f)
		var v vectorFile
		if err := json.Unmarshal(raw, &v); err != nil {
			t.Fatalf("%s: %v", f, err)
		}
		r, err := ParseID(v.Rules.ID)
		if err != nil {
			t.Fatal(err)
		}
		for _, c := range v.Cases {
			s, err := Replay(r, c.Actions)
			if c.Error != nil {
				if err == nil {
					t.Errorf("%s/%s: expected an error", v.Rules.ID, c.Name)
				}
				continue
			}
			if err != nil {
				t.Errorf("%s/%s: %v", v.Rules.ID, c.Name, err)
				continue
			}
			e := c.Expect
			if s.Board() != e.Board || s.Ply != e.Ply || phaseOf(s) != e.Phase || outcomeOf(s) != e.Outcome || s.Swapped != e.Swapped {
				t.Errorf("%s/%s: got board=%s ply=%d phase=%s outcome=%s; want %s %d %s %s", v.Rules.ID, c.Name, s.Board(), s.Ply, phaseOf(s), outcomeOf(s), e.Board, e.Ply, e.Phase, e.Outcome)
			}
			if s.Phase != Ended && s.ToMove.String() != e.ToMove {
				t.Errorf("%s/%s: toMove %s want %s", v.Rules.ID, c.Name, s.ToMove, e.ToMove)
			}
			if got := s.Legal(); !equalInts(got, e.Legal) {
				t.Errorf("%s/%s: legal %v want %v", v.Rules.ID, c.Name, got, e.Legal)
			}
			want := -1
			if e.NextToVanish != nil {
				want = *e.NextToVanish
			}
			if s.NextToVanish() != want {
				t.Errorf("%s/%s: nextToVanish %d want %d", v.Rules.ID, c.Name, s.NextToVanish(), want)
			}
		}
		for _, p := range v.Playouts {
			s, err := Replay(r, p.Actions)
			if err != nil || s.Board() != p.FinalBoard || outcomeOf(s) != p.Outcome {
				t.Errorf("%s playout %q: board %s outcome %s err %v; want %s %s", v.Rules.ID, p.Actions[:min(len(p.Actions), 30)], s.Board(), outcomeOf(s), err, p.FinalBoard, p.Outcome)
			}
		}
		if v.Tablebase != nil && r.N == 3 {
			tb := Solve(r)
			if tb.Reachable != v.Tablebase.Reachable || tb.NonTerminal != v.Tablebase.NonTerminal {
				t.Errorf("%s: tablebase %d/%d want %d/%d", v.Rules.ID, tb.Reachable, tb.NonTerminal, v.Tablebase.Reachable, v.Tablebase.NonTerminal)
			}
			for _, pos := range v.Tablebase.Positions {
				s, _ := Replay(r, pos.Actions)
				if s.Phase == AwaitingSwapDecision {
					continue
				}
				e, ok := tb.Lookup(s)
				if !ok || e.Value.String() != pos.Value || e.Distance != pos.Distance {
					t.Errorf("%s @%q: %v/%d want %s/%d", v.Rules.ID, pos.Actions, e.Value, e.Distance, pos.Value, pos.Distance)
				}
			}
		}
	}
}

func equalInts(a, b []int) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}

